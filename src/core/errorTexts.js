// Читач — директор або менеджер СТО, не розробник. Він має зрозуміти три речі: що не вийшло,
// чому, і чи потрібно щось робити самому. Тому:
//
//   • Називати сервіс на імʼя: «Binotel», «OpenAI», «ElevenLabs». «Зовнішній сервіс» нічого не
//     говорить і не допомагає ні зрозуміти, ні переказати розробнику.
//   • Короткі речення. Одна думка — одне речення.
//   • `action` починається з малої літери й у формі «що зробити», бо друкується після «Що робити:»
//     («поповнити баланс OpenAI», «нічого — відновиться саме»).
//   • Прямо казати, коли робити нічого не треба. Це найчастіша ситуація і найважливіша інформація.
//   • Прямо казати, коли потрібен розробник — щоб людина не шукала кнопку, якої немає.
//   • Про дані — завжди окремим рядком (`data`): втрачено чи ні. Це перше, що питає власник.
//   • БЕЗОСОБОВО про бота (правило проєкту): «не вдалося», а не «я не зміг».
//
// Чого тут не має бути: «на жаль», «ой», «щось пішло не так», «вибачте», знаків оклику, емодзі
// в середині речень, «будь ласка, спробуйте пізніше» без вказівки, скільки саме чекати, і слова
// «продажний» (правило проєкту — «угода»).

